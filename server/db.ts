import fs from 'node:fs';
import path from 'node:path';

/**
 * Database access with one async API and two backends:
 *  - PostgreSQL when DATABASE_URL / POSTGRES_URL is set (Vercel + Neon, or any hosted Postgres)
 *  - SQLite file otherwise (local development / single-server hosting), via Node's built-in node:sqlite
 * Queries use `?` placeholders and the SQL subset both engines share.
 */
type Param = string | number | null;
export interface Db {
  dialect: 'postgres' | 'sqlite';
  all<T>(sql: string, params?: Param[]): Promise<T[]>;
  get<T>(sql: string, params?: Param[]): Promise<T | undefined>;
  run(sql: string, params?: Param[]): Promise<{ changes: number }>;
  /** Runs fn while holding a global lock (serialises first-run setup across serverless instances). Use `tx` inside. */
  exclusive<T>(fn: (tx: Db) => Promise<T>): Promise<T>;
}

export const PG_URL = process.env.DATABASE_URL || process.env.POSTGRES_URL || '';
export const dataDir = () => path.resolve(process.env.CVFORGE_DATA_DIR ?? path.join(process.cwd(), 'server', 'data'));

const SQLITE_SCHEMA = `
  PRAGMA journal_mode = WAL;
  PRAGMA foreign_keys = ON;
  PRAGMA busy_timeout = 5000;
  CREATE TABLE IF NOT EXISTS users (
    id                   INTEGER PRIMARY KEY AUTOINCREMENT,
    username             TEXT    NOT NULL UNIQUE COLLATE NOCASE,
    password_hash        TEXT    NOT NULL,
    role                 TEXT    NOT NULL CHECK (role IN ('admin', 'user')),
    full_name            TEXT    NOT NULL DEFAULT '',
    email                TEXT    NOT NULL DEFAULT '',
    active               INTEGER NOT NULL DEFAULT 1,
    must_change_password INTEGER NOT NULL DEFAULT 0,
    created_at           INTEGER NOT NULL,
    updated_at           INTEGER NOT NULL,
    last_login_at        INTEGER,
    password_changed_at  INTEGER NOT NULL
  );
  CREATE TABLE IF NOT EXISTS sessions (
    token_hash   TEXT    PRIMARY KEY,
    user_id      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at   INTEGER NOT NULL,
    last_seen_at INTEGER NOT NULL,
    expires_at   INTEGER NOT NULL,
    user_agent   TEXT    NOT NULL DEFAULT '',
    ip           TEXT    NOT NULL DEFAULT ''
  );
  CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
  CREATE TABLE IF NOT EXISTS resumes (
    user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    id          TEXT    NOT NULL,
    name        TEXT    NOT NULL,
    template_id TEXT    NOT NULL,
    body        TEXT    NOT NULL,
    created_at  INTEGER NOT NULL,
    updated_at  INTEGER NOT NULL,
    PRIMARY KEY (user_id, id)
  );
  CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
  CREATE TABLE IF NOT EXISTS login_failures (key TEXT PRIMARY KEY, count INTEGER NOT NULL, reset_at INTEGER NOT NULL);
`;

// Postgres: BIGINT millisecond timestamps; usernames unique case-insensitively via an index on lower(username).
const PG_SCHEMA = `
  CREATE TABLE IF NOT EXISTS users (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             TEXT    NOT NULL,
    password_hash        TEXT    NOT NULL,
    role                 TEXT    NOT NULL CHECK (role IN ('admin', 'user')),
    full_name            TEXT    NOT NULL DEFAULT '',
    email                TEXT    NOT NULL DEFAULT '',
    active               INTEGER NOT NULL DEFAULT 1,
    must_change_password INTEGER NOT NULL DEFAULT 0,
    created_at           BIGINT  NOT NULL,
    updated_at           BIGINT  NOT NULL,
    last_login_at        BIGINT,
    password_changed_at  BIGINT  NOT NULL
  );
  CREATE UNIQUE INDEX IF NOT EXISTS users_username_ci ON users (lower(username));
  CREATE TABLE IF NOT EXISTS sessions (
    token_hash   TEXT    PRIMARY KEY,
    user_id      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at   BIGINT  NOT NULL,
    last_seen_at BIGINT  NOT NULL,
    expires_at   BIGINT  NOT NULL,
    user_agent   TEXT    NOT NULL DEFAULT '',
    ip           TEXT    NOT NULL DEFAULT ''
  );
  CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
  CREATE TABLE IF NOT EXISTS resumes (
    user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    id          TEXT    NOT NULL,
    name        TEXT    NOT NULL,
    template_id TEXT    NOT NULL,
    body        TEXT    NOT NULL,
    created_at  BIGINT  NOT NULL,
    updated_at  BIGINT  NOT NULL,
    PRIMARY KEY (user_id, id)
  );
  CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
  CREATE TABLE IF NOT EXISTS login_failures (key TEXT PRIMARY KEY, count INTEGER NOT NULL, reset_at BIGINT NOT NULL);
`;

async function openPostgres(): Promise<Db> {
  const { default: pg } = await import('pg');
  pg.types.setTypeParser(20, (v: string) => Number(v)); // BIGINT/COUNT(*) → number (ms timestamps fit safely)
  const local = /localhost|127\.0\.0\.1/.test(PG_URL);
  const pool = new pg.Pool({
    connectionString: PG_URL,
    max: Number(process.env.PG_POOL_MAX ?? 3),
    idleTimeoutMillis: 10_000,
    ssl: local || /sslmode=disable/.test(PG_URL) ? undefined : { rejectUnauthorized: false },
  });
  const toPg = (sql: string) => {
    let i = 0;
    return sql.replace(/\?/g, () => `$${++i}`);
  };
  type Q = { query: (sql: string, params?: Param[]) => Promise<{ rows: never[]; rowCount: number | null }> };
  const make = (q: Q): Db => {
    const db: Db = {
      dialect: 'postgres',
      all: async (sql, params = []) => (await q.query(toPg(sql), params)).rows,
      get: async (sql, params = []) => (await q.query(toPg(sql), params)).rows[0],
      run: async (sql, params = []) => ({ changes: (await q.query(toPg(sql), params)).rowCount ?? 0 }),
      exclusive: async (fn) => {
        // the lock and the work share one connection, so this can't deadlock on a small pool
        const client = await pool.connect();
        try {
          await client.query('SELECT pg_advisory_lock(727274)');
          return await fn(make(client as unknown as Q));
        } finally {
          await client.query('SELECT pg_advisory_unlock(727274)').catch(() => {});
          client.release();
        }
      },
    };
    return db;
  };
  const db = make(pool as unknown as Q);
  await db.exclusive(async (tx) => {
    for (const stmt of PG_SCHEMA.split(';').map((s) => s.trim()).filter(Boolean)) await tx.run(stmt);
  });
  return db;
}

async function openSqlite(): Promise<Db> {
  const { DatabaseSync } = await import('node:sqlite');
  const dir = dataDir();
  fs.mkdirSync(dir, { recursive: true });
  const sqlite = new DatabaseSync(process.env.CVFORGE_DB ?? path.join(dir, 'cvforge.db'));
  sqlite.exec(SQLITE_SCHEMA);
  let chain: Promise<unknown> = Promise.resolve();
  const db: Db = {
    dialect: 'sqlite',
    all: async (sql, params = []) => sqlite.prepare(sql).all(...params) as never,
    get: async (sql, params = []) => sqlite.prepare(sql).get(...params) as never,
    run: async (sql, params = []) => ({ changes: Number(sqlite.prepare(sql).run(...params).changes) }),
    exclusive: (fn) => {
      const next = chain.then(() => fn(db));
      chain = next.catch(() => {});
      return next;
    },
  };
  return db;
}

let dbPromise: Promise<Db> | null = null;
export const getDb = () => (dbPromise ??= (PG_URL ? openPostgres() : openSqlite()).then(async (db) => {
  await db.run(`INSERT INTO settings (key, value) VALUES ('allow_password_change', '1') ON CONFLICT (key) DO NOTHING`);
  return db;
}));

export interface UserRow {
  id: number;
  username: string;
  password_hash: string;
  role: 'admin' | 'user';
  full_name: string;
  email: string;
  active: number;
  must_change_password: number;
  created_at: number;
  updated_at: number;
  last_login_at: number | null;
  password_changed_at: number;
}

export async function getSetting(key: string) {
  const db = await getDb();
  return (await db.get<{ value: string }>('SELECT value FROM settings WHERE key = ?', [key]))?.value;
}
export async function setSetting(key: string, value: string) {
  const db = await getDb();
  await db.run('INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT (key) DO UPDATE SET value = excluded.value', [key, value]);
}
export const allowPasswordChange = async () => (await getSetting('allow_password_change')) !== '0';
